#!/usr/bin/env python3
"""Reads portfolio/portfolioN.(webp|jpg|jpeg|png) and writes js/portfolio-data.js
with each photo's real width/height. Re-run after adding or replacing photos."""
import os, re, struct, json, sys

def size_png(f):
    f.seek(16); return struct.unpack(">II", f.read(8))

def size_jpeg(f):
    f.seek(2)
    while True:
        b = f.read(1)
        while b and b != b"\xff": b = f.read(1)
        while b == b"\xff": b = f.read(1)
        if not b: raise ValueError("no SOF")
        m = b[0]
        if m in (0xD8, 0x01) or 0xD0 <= m <= 0xD7: continue
        n = struct.unpack(">H", f.read(2))[0]
        if m in (0xC0,0xC1,0xC2,0xC3,0xC5,0xC6,0xC7,0xC9,0xCA,0xCB,0xCD,0xCE,0xCF):
            f.read(1); h, w = struct.unpack(">HH", f.read(4)); return w, h
        f.seek(n - 2, 1)

def size_webp(f):
    f.seek(12); kind = f.read(4); f.read(4)
    if kind == b"VP8X":
        f.read(4); d = f.read(6)
        return 1 + int.from_bytes(d[0:3], "little"), 1 + int.from_bytes(d[3:6], "little")
    if kind == b"VP8L":
        f.read(1); v = struct.unpack("<I", f.read(4))[0]
        return (v & 0x3FFF) + 1, ((v >> 14) & 0x3FFF) + 1
    if kind == b"VP8 ":
        f.read(3); f.read(3); w, h = struct.unpack("<HH", f.read(4))
        return w & 0x3FFF, h & 0x3FFF
    raise ValueError("unknown webp")

def dims(path):
    with open(path, "rb") as f:
        ext = path.rsplit(".", 1)[1].lower()
        return {"png": size_png, "webp": size_webp}.get(ext, size_jpeg)(f)

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
folder = os.path.join(root, "portfolio")
found = {}
for name in sorted(os.listdir(folder)):
    m = re.fullmatch(r"portfolio(\d+)\.(webp|jpe?g|png)", name, re.I)
    if not m: continue
    n = int(m.group(1))
    rank = ["webp", "jpg", "jpeg", "png"].index(m.group(2).lower())
    if n in found and found[n][0] <= rank: continue   # prefer webp, same order as before
    w, h = dims(os.path.join(folder, name))
    found[n] = (rank, "portfolio/" + name, w, h)

data = {str(n): [v[1], v[2], v[3]] for n, v in sorted(found.items())}
out = os.path.join(root, "js", "portfolio-data.js")
with open(out, "w") as f:
    f.write("/* AUTO-GENERATED by tools/gen-portfolio-data.py - do not edit by hand. */\n")
    f.write("window.PORTFOLIO_SIZES = {\n" + ",\n".join(" %s: %s" % (k, json.dumps(v)) for k, v in data.items()) + "\n};\n")
print("Wrote", out, "with", len(data), "photos")
